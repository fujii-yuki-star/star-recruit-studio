// 「端の目安を出すか」の記憶（#265）。
//
// ⚠️ **画面の好みなので覚える**（ADR-0033・ADR-0034 決定14）＝倍率（文書の見え方）と違い、
// これは**その人の作り方**。開き直すたびに消えると毎回入れ直すことになる。
//
// ⚠️ **画面ごとではなくアプリで1つ**＝節の開閉（画面ごとに顔ぶれが違う）と違い、これは
// 「端で切られないように作る人か」という**1つの好み**なので、場面編集で入れたのに
// 見た目パターン編集では消えている、を作らない。
//
// ⚠️ **仕組みは `booleanPref` に寄せた**（#1103）＝左の帯の開閉が同じ形になったので、
// 「この場の正はモジュールの変数」「覚えられなくても効かせる」「合図で他の使い手へ知らせる」を
// 二重に持たない。**鍵と合図の名前は据え置き**＝変えると利用者の記憶が消える。
import { createBooleanPref } from "./booleanPref";

/** 覚えの置き場。⚠️ **気軽に変えない**＝変えると利用者の記憶が消える。 */
export const SAFE_AREA_KEY = "preview.safeArea";
/**
 * 覚えが無いときの姿＝**目安は出さない**。
 *
 * ⚠️ **名前を付けて外へ出す**（レビュー 🟡・#1103）＝呼び出しの中に `false` と書いたままだと、
 * 検査が毎回 `resetSafeAreaPrefTo(false)` で正を上書きしてから描くので、
 * **この既定を一度も通らない**（`true` に書き換えても全部緑のまま）。
 * ⚠️ **この穴は寄せる前からあった**（回帰ではない）＝**双子の片方だけ直さない**ので、
 * 左の帯（#1103）と同時に塞ぐ。
 */
export const SAFE_AREA_DEFAULT = false;

const pref = createBooleanPref(SAFE_AREA_KEY, "stario:safe-area-changed", SAFE_AREA_DEFAULT);

/**
 * 「端の目安を出すか」と、その切り替え。
 *
 * ⚠️ **同じ画面の複数の入口で食い違わない**＝切り替えとプレビューは別の場所に居るので、
 * 合図（`CustomEvent`）で他の使い手へも知らせる。
 */
export const useSafeAreaPref = pref.usePref;

/** テスト用＝この場の正を入れ直す。 */
export const resetSafeAreaPrefTo = pref.resetTo;
