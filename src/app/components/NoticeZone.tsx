import type { ReactNode } from "react";

/**
 * 画面ぜんぶに効く知らせ・確認の置き場（#940）。**スクロールしても消えない**。
 *
 * ⚠️ **貼り付ける理由**＝知らせは画面の先頭に出るのに、それを引き起こす操作は**一覧の下の方**にある
 * （動画を開く・複製する・消す・名前を変える／素材を消す・直す）。`.main-scroll` の中に置いたままだと、
 * 下まで送って押したとき**確認が視野の外**に出る。そのあいだ一覧は押せなくなるので、利用者からは
 * 「一覧が固まった」だけに見える（§2-5＝次の行動が見えない）。
 * ⚠️ **`scrollIntoView` では直したことにならない**＝押した場所から視線が飛ぶうえ、もう一度スクロールすれば
 * また消える。`06 §2` 統一規約9（#774）の「**移した先が一緒に流れていくなら直したことにならない**」に当たる。
 * 同規約が採った手（`.editor-header`＝貼り付ける）に合わせる。
 * ⚠️ **その行・その欄だけの知らせはここに入れない**＝押した場所のすぐそばに出すのが正しい
 *（見た目パターン画面の作成フォーム・削除の並びがその流儀）。ここは**画面ぜんぶに効くもの**だけ。
 */
export const NOTICE_ZONE_CLASS = "notice-zone";

export function NoticeZone({ children }: { children: ReactNode }) {
  // 中身が無いときは高さ 0＝何も描かれない（空の帯を出さないため、この入れ物自身は余白を持たない）。
  return <div className={NOTICE_ZONE_CLASS}>{children}</div>;
}
