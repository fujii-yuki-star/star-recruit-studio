// 頼まれごとを断ったときに、**どの文を理由として返すか**（#1212・#1217 レビュー 🟡）。**純粋関数**。
//
// ⚠️ **なぜ関数にするか**＝画面の中に式で書いていたら、**2つの守りが互いを隠して**、
// どちらも検査できていなかった（変異チェックで両方が生き残った）＝
// 「文を出さない枝」を壊しても**既定文が受け止める**ので緑、
// 「その回の文か見る」を壊しても**枝が文を出している**ので緑。
// 1つずつ壊せる形（＝純粋関数）にして、初めてどちらも留められる。

/**
 * 断りの理由として返す文を決める。
 *
 * ⚠️ **いちばん避けたいのは「直前の成功の文が、失敗の理由として出る」**＝
 * 頼んだ側（外の AI）は「保存しました」を**断りの理由**として受け取ることになり、
 * 何が起きたのか**まったく分からなくなる**（数字だけより悪い）。
 *
 * @param shown いま画面に出ている文（`null`/空＝出ていない）。
 * @param atStart **この回が始まった時点**で出ていた文。⚠️ **同じなら「この回の文ではない」**。
 * @param fallback どちらも使えないときの既定文（§2-5＝次の行動を示す文）。
 */
export function refusalReason(
  shown: string | null | undefined,
  atStart: string | null | undefined,
  fallback: string,
): string {
  if (!shown) return fallback;
  if (shown === atStart) return fallback;
  return shown;
}
