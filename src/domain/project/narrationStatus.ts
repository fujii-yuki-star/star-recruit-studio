// 読み上げ音声の**印**（`status`）の決め方（純粋・副作用なし・§7 テスト対象）。
//
// ⚠️ **印は文書に残る**＝一時的な失敗をそのまま書くと、開き直しても「声を作れませんでした」と出続ける。
// 前に作った声が残っているなら、その声は**そのまま鳴って動画にも入る**（タイムライン形式は `voicePath`、
// 場面形式は保存済みの音声を復元して鳴らす）＝「作れませんでした」と言いながら声は鳴る、という
// 食い違いが永続化されていた（#755-3）。
//
// ⚠️ **見るのは「声のファイルがあるか」ではなく「作り始める前の印」**（レビューで3観点が独立に指摘）。
// 場面形式の単独ナレーションは**セリフや話し方を変えても `voicePath` を落とさない**ので、ファイルの
// 有無で決めると「文を直す → 作り直しに失敗 → **古い文の声が『作成済み』に復帰**」する。そのまま
// 書き出すと**新しい字幕に古い声が乗った動画**が成功として出る（ADR-0026④が禁じているもの）。
// 「作り始める前が `generated` だった」＝その声は**いまの文のもの**と文書が言っていた、という意味なので、
// そこだけ据え置けば安全に判定できる。
import { NARRATION_STATUS } from '../enums';
import type { NarrationStatus } from '../enums';

/**
 * 声を作れなかったときに**残す印**。
 *
 * - 作り始める前が `generated`＝いまの文の声が既にある → **印は据え置く**（失敗は**その場の知らせ**で
 *   伝える＝文書に嘘を書かない・§2-5／ADR-0026①）。
 * - それ以外（`none`＝まだ作っていない／文を変えた、など）→ `failed`（作れていないことを次に開いたときも知らせる）。
 *
 * @param before **作り始める前**の印（`pending` を書く前に控えておくこと）
 */
export function statusAfterVoiceFailure(before: NarrationStatus): NarrationStatus {
  return before === NARRATION_STATUS.generated ? NARRATION_STATUS.generated : NARRATION_STATUS.failed;
}
