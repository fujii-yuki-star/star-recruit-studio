// 文書の版とアプリが知る版の**新旧比較**（#793・両形式で共有）。
//
// ⚠️ **「壊れている」と「新しすぎる」を分ける**ための道具。両形式とも、これまでは
// **同じメジャーなら通し**てから ajv にかけていたので、**アプリより新しいマイナー版**の文書は
// 「この動画の内容が正しくありません／プロジェクトの内容が正しくありません」で断られていた。
// これは**嘘**＝壊れておらず、**アプリを更新すれば開ける**（§2-5＝別の動画を選んでも解決しない）。
//
// ⚠️ もう1つ実害がある＝両形式の migrate は版を**現行へ書き換える**だけなので、未来の版の文書を
// そのまま通すと**版の印が黙って下がる**（1.9 の文書が 1.8 として開かれる）。ここで先に止める。

/** `"1.25"` のような版を数の組にする。数でない部分は 0 として扱う（壊れた値は呼び出し側の検証へ）。 */
function parts(version: string): [number, number] {
  const [major, minor] = version.split('.');
  const n = (s: string | undefined): number => {
    const v = Number(s);
    return Number.isFinite(v) ? v : 0;
  };
  return [n(major), n(minor)];
}

/**
 * 文書の版が、アプリが知る版より**新しい**か。
 *
 * ⚠️ **同じメジャーの中だけで見る**＝メジャーが違う場合は、両形式とも**先に別の関門**
 * （`isSupportedSchemaVersion` / `isSupportedTimelineSchemaVersion`）が断っており、
 * そちらは既に「アプリを更新してください」と正しく案内している。ここが受け持つのは
 * **その関門を通り抜ける「同メジャーで新しいマイナー」**だけ。
 *
 * ⚠️ **マイナーを数で比べる**＝文字列比較だと `"1.9" > "1.10"` になり、**9 のほうが新しい**と
 * 誤判定する（版が2桁に入った時点で壊れる。場面形式は既に 1.25）。
 */
export function isNewerSchemaVersion(docVersion: string, appVersion: string): boolean {
  const [dMajor, dMinor] = parts(docVersion);
  const [aMajor, aMinor] = parts(appVersion);
  if (dMajor !== aMajor) return false;
  return dMinor > aMinor;
}

