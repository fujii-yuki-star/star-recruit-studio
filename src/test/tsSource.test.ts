// TS を1回なぞる道具（`scanTs`）そのものを見る（#1142）。
//
// ⚠️ **拾い方を直接叩く**＝ディレクトリを歩く形だけだと、「拾い方を消しても、いまのコードに
// 漏れが無いので緑」になる（#981・#1140 で実際に踏んだ）。ここは**入口の1文字目から**確かめる。
import { describe, expect, it } from "vitest";
import { scanTs } from "./tsSource";

/** 拾った中身だけを並べる（位置は別の検査で見る）。 */
const 中身 = (src: string): string[] => scanTs(src).literals.map((l) => l.text);

describe("scanTs（TS を1回なぞる）", () => {
  it("説明は落とす（画面の文ではない）", () => {
    expect(中身(`// テンプレートを選ぶ\nconst a = "見た目パターンを選ぶ";`)).toEqual(["見た目パターンを選ぶ"]);
    expect(中身(`/* テンプレート */ const a = "見た目";`)).toEqual(["見た目"]);
  });

  // ⚠️ **ここを間違えると、その行の残りが見えなくなる**（Rust の `'"'` と同じ型＝#1111）。
  it("文字列の中の `//` を説明と取り違えない", () => {
    expect(中身(`const u = "http://example.com"; const m = "見つかりません";`)).toEqual([
      "http://example.com",
      "見つかりません",
    ]);
  });

  // ⚠️ **これが #1142 の本題**＝同じ文言をバッククォートで書くと走査から消えていた。
  it("テンプレート文字列も拾う", () => {
    expect(中身("const a = `選び直してください`;")).toEqual(["選び直してください"]);
  });

  // ⚠️ **繋げない**＝`${…}` の前後は別の文。繋げると**存在しない文**ができる。
  it("テンプレートは `${…}` で割る", () => {
    expect(中身("const a = `見つかりません（${n}件）。選び直してください`;")).toEqual([
      "見つかりません（",
      "件）。選び直してください",
    ]);
  });

  it("`${…}` の中の文字列も拾う（入れ子）", () => {
    expect(中身('const a = `外側${b ? "内側です" : ""}外側2`;')).toEqual(["外側", "内側です", "", "外側2"]);
  });

  it("入れ子のテンプレートでも対応が飛ばない", () => {
    // 外→（内の2つ）→外、の順で出る＝入れ子を数えているので外の残りが迷子にならない
    expect(中身("const a = `外${`中${x}中2`}外2`;")).toEqual(["外", "中", "中2", "外2"]);
  });

  // ⚠️ **正規表現の中の引用符・バッククォートで対応を反転させない**＝反転すると、
  //   その後ろの文字列が**1つも拾えなくなる**（見落とす側に倒れるので赤くならない）。
  it("正規表現の中の引用符で対応が飛ばない", () => {
    expect(中身(`const r = /['"\`]/g; const m = "見つかりません";`)).toEqual(["見つかりません"]);
  });

  // ⚠️ **割り算を正規表現と読むと、次の `/` までが丸ごと消える**。
  it("割り算を正規表現と取り違えない", () => {
    expect(中身(`const x = a / b; const m = "見つかりません"; const y = c / d;`)).toEqual(["見つかりません"]);
  });

  it("`return /…/` は正規表現として読む", () => {
    expect(中身(`function f() { return /['"]/.test(s); } const m = "見つかりません";`)).toEqual(["見つかりません"]);
  });

  // ⚠️ **座標を保つ**＝行番号も、位置の突き合わせも狂わないための約束（`rustSource` と同じ）。
  it("長さと行を保つ", () => {
    const src = `// 説明\nconst a = "あいう";\nconst b = \`かきく\${x}けこ\`;\n`;
    const { code } = scanTs(src);
    expect(code.length, "長さが変わった＝位置の突き合わせが狂う").toBe(src.length);
    expect(code.split("\n").length, "行が変わった").toBe(src.split("\n").length);
    expect(code.includes("あいう"), "文字列の中身が本文に残っている").toBe(false);
  });

  // ⚠️ **JSX の本文は残す**＝タグとタグの間の文は引用符の中に無いので、`code` を見て拾う側がある。
  it("JSX のタグと本文は残す", () => {
    const { code } = scanTs(`<p className="notice">まだありません</p>`);
    expect(code).toContain(">まだありません<");
    expect(code, "属性の値は落とす").not.toContain("notice");
  });

  // ⚠️ **上の検査だけでは穴が隠れる**（#1174 レビュー由来 🟡）＝`</p>` の後ろに中身が無いので、
  //   閉じタグの `/` から先を落としても「>まだありません<」は残って**緑になる**。
  //   ここから下の3つは、**タグの後ろに本文がある**形＝落とすと必ず赤くなる。
  it("自己終了タグ（`/>`）を正規表現と読まない", () => {
    // ⚠️ **実際に踏んだ**＝`/>` の `/` から行末までを落としていたので、この repo の定番である
    //   「アイコン＋ラベル」の書き方で**画面のラベルが 28 件消えて**いた。
    const src = `<button>\n  <Icon size={16} className="nav-icon" />\n  テンプレートを選ぶ\n</button>`;
    expect(scanTs(src).code, "自己終了タグの後ろの本文が落ちている").toContain("テンプレートを選ぶ");
  });

  it("閉じタグ（`</`）を正規表現と読まない", () => {
    const { code } = scanTs(`<b>あ</b><i>い</i>`);
    expect(code, "閉じタグの後ろの要素が落ちている").toContain(">い<");
  });

  it("自己終了タグの後ろの属性文字列も拾う", () => {
    expect(中身(`<Icon size={16} /> <span title="テンプレートを選ぶ">x</span>`)).toContain("テンプレートを選ぶ");
  });

  // ⚠️ **同じ行に閉じの `/` がある形で見る**（#1174 の変異チェックで生き残った）＝
  //   行末で終わる形だと「閉じていなければ落とさない」が肩代わりして**緑になり**、
  //   `/>` の見分けそのものを検査していないことに気づけない。
  it("自己終了タグ（`/>`）＝同じ行に `/` が続いても巻き込まない", () => {
    const { code } = scanTs(`<Icon className="x" /><b>あ/い</b>`);
    expect(code, "`/>` から次の `/` までを巻き込んでいる").toContain(">あ/い<");
  });

  // ⚠️ **閉じていない `/` で行末まで落とさない**（#1174 レビュー由来 🔴）＝
  //   「落としすぎない側へ倒す」と書いたコメントと**実装が逆**だった（行末まで落としていた）。
  it("閉じていない `/` は落とさない（同じ行の後ろを巻き添えにしない）", () => {
    expect(中身(`const a = /閉じ忘れ; const m = "見つかりません";`)).toContain("見つかりません");
  });

  // ⚠️ **この repo に実在する形**＝`場面 {i} / {n}`・`<span>{title.length}/{MAX}</span>`。
  it("`}` の後ろの `/` を正規表現と読まない（JSX の本文・割り算）", () => {
    const { code } = scanTs(`<span>{title.length}/{MAX}</span><b>あ</b>`);
    // ⚠️ **隣の要素ではなく、巻き込まれる側を見る**（変異チェックで生き残った）＝
    //   `>あ<` は無事なままなので、それだけ見ていると**落ちたことに気づけない**。
    expect(code, "閉じタグごと落ちてタグの対応が狂っている").toContain("</span>");
    expect(code).toContain(">あ<");
  });

  // ⚠️ **`${…}` の中だけ見分けていなかった**（#1174 レビュー由来 🟡）＝この道具が
  //   いちばん断ちたかった「対応の反転」が、中にだけ残っていた。
  it("`${…}` の中の正規表現でも対応が飛ばない", () => {
    const src = 'const a = `前${s.replace(/[\'"]/g, "")}後`; const m = "見つかりません";';
    expect(中身(src)).toEqual(["前", "", "後", "見つかりません"]);
  });

  it("閉じていない文字列で暴走しない（行で止める）", () => {
    expect(中身(`const a = "閉じ忘れ\nconst b = "見つかりません";`)).toContain("見つかりません");
  });
});
