// 「その文が**次の行動**を示しているか」の物差し（§2-5）。
//
// ⚠️ **1か所に置く**（PR #1130 レビューと同じ理由）＝以前は `rustUserMessageGuard.test.ts` の中にあり、
// **別の門番から使うには検査 file を import する**しかなかった（その file の検査まで走ってしまう）。
// 物差しを写せば、片方だけ広げても黙って通る形になる（`hasJapanese` で実際に起きた）。

/**
 * その文が**次の行動**を示しているか（§2-5）。
 *
 * ⚠️ **「〜してください」以外の形もある**＝「完了までお待ちください」は待つことが次の行動。
 * 逆に「〜に失敗しました。」で終わる文は、**何をすればよいか誰にも分からない**。
 */
export function showsNextAction(message: string): boolean {
  return /ください/.test(message);
}
